def main() -> int:
    text = DRUGS_YAML.read_text(encoding="utf-8")
    data = yaml.safe_load(text) or {}
    ings = {i["name_cn"] for i in data.get("ingredients", [])}
    have_names = {d["name_cn"] for d in data.get("drugs", [])}

    missing_ing = {ing for _, _, ing, _ in NEW_DRUGS if ing not in ings}
    if missing_ing:
        print(f"成分不存在，先修正: {missing_ing}")
        return 1

    to_add = [d for d in NEW_DRUGS if d[0] not in have_names]
    if not to_add:
        print("没有缺失条目，不做修改")
        return 0

    if MARKER not in text:
        text = text.rstrip("\n") + (
            "\n\n  # ── 剂型扩充（scripts/augment_drugs.py 生成，"
            "待药师核验；未填规格/商品名/批准文号）──\n"
        )

    block = []
    for name, form, ing, otc in to_add:
        block.append(
            f"  - name_cn: {name}\n"
            f"    dosage_form: {form}\n"
            f"    is_otc: {otc}\n"
            f"    ingredients: [{{name: {ing}}}]\n"
        )
    DRUGS_YAML.write_text(text + "".join(block), encoding="utf-8")
    print(f"追加 {len(to_add)} 条药品 → {DRUGS_YAML.relative_to(ROOT)}")
    print(f"药品总数: {len(have_names)} → {len(have_names) + len(to_add)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
